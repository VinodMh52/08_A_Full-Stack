 class DataTypeDemo{
    public static void main( String [] args ){

        int a=10;
        float b=2.2f;
        double c= 55.55;
        char d= 'A';
        boolean e=true;

        System.out.println("Integear :" +a);
        System.out.println("Float :" +b);
        System.out.println("Double :"+c);
        System.out.println("Char :"+d);
        System.out.println("Boolean :"+e);
    }
 }